// ============================================================================
// gen-account-wide-talents.ts — the talent ids the game reads "best across all
// characters": every `_customBlock_getbonus2(line, id, -1)` call in the live
// N.js (getbonus2 with -1 loops PlayerDATABASE and keeps the highest value).
// Output: web/lib/arkh/stats/data/common/account-wide-talents.gen.ts
//
// Reads the full game code the updater downloads (scripts/updater/.cache/
// N.new.js); the formulas snapshot misses the calls that sit in scene code
// (204, 370, 535, 585, 595). Re-run after the updater fetched a new N.js.
//
// Run with: npx tsx web/scripts/gen-account-wide-talents.ts
// ============================================================================

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { TalentIconNames } from "@/lib/game/data/generated/customlists.js";

const NJS = resolve(__dirname, "updater", ".cache", "N.new.js");
const OUT = resolve(__dirname, "..", "lib", "arkh", "stats", "data", "common", "account-wide-talents.gen.ts");

if (!existsSync(NJS)) {
  console.error(`Missing ${NJS} — run the updater (scripts/updater/run.ts) first.`);
  process.exit(1);
}
const src = readFileSync(NJS, "utf8");
const ids = new Set<number>();
for (const m of src.matchAll(/getbonus2\(\s*[^,()]+?\s*,\s*(\d+)\s*,\s*-1\s*\)/g)) ids.add(Number(m[1]));
if (ids.size === 0) throw new Error("no getbonus2(…, -1) calls found — N.js layout changed?");

const names = TalentIconNames as unknown as string[];
const lines = [
  "// AUTO-GENERATED by web/scripts/gen-account-wide-talents.ts — do not edit by hand.",
  "// Source: every _customBlock_getbonus2(line, id, -1) call in N.js (best across characters).",
  "// Regenerate: npx tsx web/scripts/gen-account-wide-talents.ts",
  "",
  "export const GETBONUS2_BEST_ACROSS_CHARS_IDS: readonly number[] = [",
  ...[...ids].sort((a, b) => a - b).map((id) => `  ${id}, // ${names[id] ?? "?"}`),
  "];",
  "",
];
writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} (${ids.size} ids)`);
