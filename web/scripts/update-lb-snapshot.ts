// Daily snapshot of every Idleon Toolbox leaderboard's #10 / #100 cutoffs plus the tab/section structure,
// written to lib/leaderboards/snapshot.ts. Used for "points to reach the top 100" and as the fallback when
// IT's live /meta fails. Makes 221 requests a day (1 meta + 1 per board), under the access agreed with
// Idleon Toolbox's owner (Origin + our scraper UA; ask before going past ~2,000 a day).
//
// Run (from web/):  npx tsx scripts/update-lb-snapshot.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { SCRAPER_HEADERS } from "../lib/leaderboards/itFetch";
import type { BoardCutoffs, LB_SNAPSHOT } from "../lib/leaderboards/snapshot";
import type { LbBoard, LbMeta } from "../lib/leaderboards/types";

const BASE = "https://profiles.idleontoolbox.workers.dev/api";
const MIN_BOARDS = 200;
type Snapshot = { meta: LbMeta; boards: Record<string, BoardCutoffs> };

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

export async function buildSnapshot(
  fetchJson: (url: string) => Promise<unknown>,
  previous: typeof LB_SNAPSHOT | null,
  today: string,
  delayMs = 500,
): Promise<Snapshot> {
  const meta = (await fetchJson(`${BASE}/leaderboards/meta`)) as LbMeta;
  const keys = meta.tabs.flatMap((t) => t.sections.flatMap((s) => s.metrics.map((m) => m.key)));
  const boards: Record<string, BoardCutoffs> = {};
  for (const key of keys) {
    if (delayMs) await sleep(delayMs);
    try {
      const { top } = (await fetchJson(`${BASE}/leaderboards/board?metric=${encodeURIComponent(key)}&limit=100`)) as LbBoard;
      if (!top?.length) continue;
      boards[key] = {
        top10: top[9]?.value,
        top100: top[99]?.value,
        lowerIsBetter: top[0].value < top[top.length - 1].value,
        firstSeen: previous?.boards[key]?.firstSeen ?? today,
      };
    } catch {
      // skipped; counted below
    }
  }
  const n = Object.keys(boards).length;
  if (n < MIN_BOARDS) throw new Error(`only ${n} boards fetched`);
  return { meta, boards };
}

export function renderSnapshot(s: { generatedAt: string; meta: LbMeta; boards: Record<string, BoardCutoffs> }): string {
  return `// Generated by scripts/update-lb-snapshot.ts (daily cron). Do not edit by hand.
import type { LbMeta } from "./types";

export type BoardCutoffs = { top10?: number; top100?: number; lowerIsBetter: boolean; firstSeen: string };
export const LB_SNAPSHOT: { generatedAt: string; meta: LbMeta; boards: Record<string, BoardCutoffs> } = ${JSON.stringify(s, null, 1)};
`;
}

async function fetchJson(url: string): Promise<unknown> {
  const r = await fetch(url, { headers: SCRAPER_HEADERS });
  if (!r.ok) throw new Error(`HTTP ${r.status} ${url}`);
  return r.json();
}

async function main(): Promise<void> {
  const { LB_SNAPSHOT: previous } = await import("../lib/leaderboards/snapshot");
  const s = await buildSnapshot(fetchJson, previous.meta.tabs.length ? previous : null, new Date().toISOString().slice(0, 10));
  writeFileSync(join(__dirname, "../lib/leaderboards/snapshot.ts"), renderSnapshot({ generatedAt: new Date().toISOString(), ...s }));
  console.log(`✓ ${Object.keys(s.boards).length} boards`);
}

if (require.main === module)
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
