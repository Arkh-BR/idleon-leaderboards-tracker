// web/scripts/updater/registry/gen-registry.ts
// Builds the formula registry. It maps each N.js formula/mirrored-constant name
// to the file(s) that port it, from two sources:
//   - `// @njs <name>` annotations across the ported engines (regex scan: simple
//     and enough for "which file(s) to review"), lib/game/njs included for what a
//     module mirrors without a block of its own;
//   - lib/game/njs, where the module IS the link (spec §1): each
//     `block("<Fn>", …)` is `_customBlock_<Fn>` and each `case "<Sub>":` of its
//     dispatcher is the named block `<Sub>`.
// Run via gen() to (re)write the .gen.ts (from web/: npx tsx scripts/updater/registry/gen-registry.ts).
import { existsSync, readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const __dirname = dirname(fileURLToPath(import.meta.url));
export const WEB_ROOT = join(__dirname, "../../..");
const ROOTS = ["lib/arkh", "lib/tome", "lib/cookingMastery", "lib/talentsLevel", "lib/dropRate", "lib/coinMulti"];
const GAME_ROOT = "lib/game/njs";
// First char may be "_": the snapshot keys N.js functions as _customBlock_*.
const ANNOT = /\/\/\s*@njs\s+([A-Za-z_][A-Za-z0-9_]*(?:\[[0-9]+\])?)/g;

function walk(dir: string, acc: string[]): string[] {
  let entries: string[] = [];
  try { entries = readdirSync(dir); } catch { return acc; }
  for (const e of entries) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (e.endsWith(".ts")) acc.push(p);
  }
  return acc;
}

/**
 * The N.js names a lib/game module ports. `block("DNSM.StarSigns", …)` (a cache of the game, not a `_customBlock_`) is skipped. A `case`
 * of a sub-case's own body (an inner switch) is not the dispatcher's: the walk stops at each clause.
 */
export function gameNames(file: string, text: string): string[] {
  const names: string[] = [];
  const cases = (n: ts.Node): void => {
    if (ts.isCaseClause(n)) {
      if (ts.isStringLiteralLike(n.expression)) names.push(n.expression.text);
      return;
    }
    ts.forEachChild(n, cases);
  };
  const visit = (n: ts.Node): void => {
    if (ts.isCallExpression(n) && ts.isIdentifier(n.expression) && n.expression.text === "block" && n.arguments.length >= 2) {
      const [name, fn] = n.arguments;
      if (ts.isStringLiteralLike(name) && /^[A-Za-z_][A-Za-z0-9_]*$/.test(name.text)) {
        names.push(`_customBlock_${name.text}`);
        cases(fn);
        return;
      }
    }
    ts.forEachChild(n, visit);
  };
  visit(ts.createSourceFile(file, text, ts.ScriptTarget.Latest));
  return names;
}

export function buildRegistry(webRoot: string = WEB_ROOT): Record<string, string[]> {
  const map: Record<string, string[]> = {};
  for (const root of [...ROOTS, GAME_ROOT]) {
    for (const file of walk(join(webRoot, root), [])) {
      const txt = readFileSync(file, "utf8");
      let m: RegExpExecArray | null;
      ANNOT.lastIndex = 0;
      while ((m = ANNOT.exec(txt))) {
        const rel = relative(webRoot, file).replace(/\\/g, "/");
        (map[m[1]] ??= []).push(rel);
      }
    }
  }
  // A sub-case is registered only if the snapshot has it as a named block: the extractor reads `if("X"==d)`, not N.js's ternary form
  // (`"X"==d?…:`), and a change to one of those shows in the scaffold of its `_customBlock_<Fn>`, which is always registered (and which
  // the guard test checks against the snapshot, so a block name that is not N.js's fails there).
  const snap = join(webRoot, "data/njs-snapshot/formulas.json");
  const named = existsSync(snap) ? new Set(Object.keys(JSON.parse(readFileSync(snap, "utf8")))) : null;
  for (const file of walk(join(webRoot, GAME_ROOT), [])) {
    const rel = relative(webRoot, file).replace(/\\/g, "/");
    for (const name of gameNames(file, readFileSync(file, "utf8"))) {
      if (name.startsWith("_customBlock_") || !named || named.has(name)) (map[name] ??= []).push(rel);
    }
  }
  for (const k of Object.keys(map)) map[k] = [...new Set(map[k])].sort();
  return map;
}

export function renderRegistry(map: Record<string, string[]>): string {
  const sorted: Record<string, string[]> = {};
  for (const k of Object.keys(map).sort()) sorted[k] = map[k];
  return (
    "// AUTO-GENERATED by registry/gen-registry.ts — DO NOT EDIT.\n" +
    "// Maps each N.js formula / mirrored-constant (@njs annotations, and the blocks of lib/game/njs) to the ported file(s).\n" +
    "export const FORMULA_REGISTRY: Record<string, string[]> = " +
    JSON.stringify(sorted, null, 2) +
    ";\n"
  );
}

function gen(): void {
  const out = join(__dirname, "formula-registry.gen.ts");
  writeFileSync(out, renderRegistry(buildRegistry()), "utf8");
  console.log(`[registry] wrote ${out} (${Object.keys(buildRegistry()).length} entries)`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) gen();
