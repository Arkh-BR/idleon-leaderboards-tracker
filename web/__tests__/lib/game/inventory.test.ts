// The committed Damage and AFK inventories are the generator's output (scripts/njs-closure.ts --mark): `[x]` from the modules' PORTED, `[~]` from
// lib/game/unreached.ts, nothing marked by hand. A change to either, or a new N.js, without a regeneration fails here. The generator reads
// the live N.js cache (gitignored), so this skips without it.
import { describe, expect, it } from "vitest";
import { existsSync, readFileSync } from "node:fs";
import { UNREACHED } from "@/lib/game/unreached";

const NJS = "scripts/updater/.cache/N.new.js";
const INVENTORIES = {
  Damage: "../docs/superpowers/plans/2026-11-04-damage-inventory.md",
  AFK: "../docs/superpowers/plans/2026-11-05-afk-gains-inventory.md",
};
const COMMAND = /Generated by `cd web && npx tsx scripts\/njs-closure\.ts ([^`]+)`/;

describe.skipIf(!existsSync(NJS)).each(Object.entries(INVENTORIES))("the %s inventory", (name, INVENTORY) => {
  it("equals the generator's output for the command in its header (regenerate it with that command)", async () => {
    const { inventoryText } = await import("@/scripts/njs-closure");
    const md = readFileSync(INVENTORY, "utf8").replace(/\r\n/g, "\n");
    const argv = md.match(COMMAND)?.[1].split(" ");
    expect(argv?.[0]).toBe("--mark");
    expect(md).toBe(await inventoryText(argv!));
  }, 600_000);

  it("has every row lib/game/unreached.ts declares, as [~]", () => {
    const md = readFileSync(INVENTORY, "utf8");
    // unreached.ts rows are per root (Damage's); the equality test above covers the AFK inventory
    if (name !== "Damage") return;
    for (const u of UNREACHED) expect(md, u.row).toContain(`- [~] ${u.row} —`);
  });
});
